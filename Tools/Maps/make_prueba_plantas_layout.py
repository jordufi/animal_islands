# Builds Assets/Maps/PruebaPlantas/PruebaPlantas_Layout.txt: the small test map for real floors (Docs/PLANTAS_FORMATO.md).
# Run:  python Tools/Maps/make_prueba_plantas_layout.py [--check] [--png]
# Three floors: a (start) and g on the ground floor (g is double height: a void above it with a gallery round it),
# a switchback stair a -> c (door 2 at its foot), c on the 1st floor, a stair c -> d (door 3 at its foot), d an open
# roof with railings to the outside. A lift serves the three floors, a chute drops from the roof to a, and a service
# door ($) joins a and b besides the paid door 1.
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from floors import Plan  # noqa: E402

P = Plan(24, 16)
F0 = P.floor('0', 'Planta baja', 0)
F1 = P.floor('1', 'Primera planta', 2)
F2 = P.floor('2', 'Azotea', 4)
P.zones = [
    ('a', 'Entrada', 'Entrada', 0, 'B79A6E', 'start techo'),
    ('g', 'Sala', 'Sala doble', 1, '8FA0B8', 'techo'),
    ('c', 'Primera', 'Primera planta', 2, 'A0523C', 'techo'),
    ('d', 'Azotea', 'Azotea', 3, '8C8C8C', ''),
]
P.doors = [
    ('1', 'Puerta de la sala', 500, 'a g', ''),
    ('2', 'Escalera', 750, 'a c', ''),
    ('3', 'Escalera de la azotea', 1000, 'c d', ''),
]

# base fills first
F0.fill(0, 0, 23, 15, '#'); F0.fill(2, 2, 9, 13, 'a'); F0.fill(11, 2, 21, 13, 'g')
F1.fill(0, 0, 23, 15, '#'); F1.fill(2, 2, 21, 13, 'c'); F1.fill(12, 4, 16, 9, '~')
F2.fill(2, 2, 21, 13, 'd')

# ground floor
F0.marks('1', (10, 7), (10, 8)); F0.put(10, 11, '$')
F0.marks('o', (15, 12), (18, 4))
F0.marks('@', (5, 12)); F0.marks('B', (2, 13)); F0.marks('D', (21, 7))
F0.marks('s', (2, 2), (9, 13), (21, 2), (21, 13), (13, 13), (9, 2))
F0.marks('2', (4, 11)); F0.put(4, 10, 'c'); F0.marks('#', (3, 10), (5, 10))
P.stair(F0, (4, 10), (0, -1), (1, 0), 'c')            # arrives on the 1st floor at (6, 10)

# first floor
F1.put(20, 11, 'd'); F1.marks('3', (20, 12)); F1.marks('#', (19, 11), (21, 11))
P.stair(F1, (20, 11), (0, -1), (-1, 0), 'd')          # arrives on the roof at (18, 11)
F1.marks('B', (21, 13)); F1.marks('s', (2, 2), (21, 2), (2, 13), (11, 13))
F1.marks('x', (9, 4))

# roof
F2.marks('o', (6, 6), (12, 4))
F2.marks('b', (10, 7)); F2.marks('X', (14, 12))
F2.marks('s', (2, 2), (21, 2), (2, 13), (21, 13), (11, 2))

P.lift('A', 'Ascensor', 1, 4, ['0', '1', '2'])
P.link('1', 'Tolva de prueba', ('2', 5, 12), ('0', 8, 3), 'tolva')
P.point('servicio', '0', 10, 11)

TITLE = 'Prueba de plantas (mapa de prueba del formato con plantas reales)'
HEADER = """# Prueba de plantas - test map for real floors (Tools > Island > Setup Prueba de plantas).
# GENERATED by Tools/Maps/make_prueba_plantas_layout.py. Format: Docs/PLANTAS_FORMATO.md.
"""
problems, warnings = P.check()
P.show(heights='--heights' in sys.argv)
print('PROBLEMS:' if problems else 'checks OK')
for p in problems:
    print('  ' + p)
if '--png' in sys.argv:
    P.draw(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'Renders', 'Plano_PruebaPlantas.png'), TITLE, cols=3)
if '--check' not in sys.argv and not problems:
    P.write(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'Assets', 'Maps', 'PruebaPlantas', 'PruebaPlantas_Layout.txt'), HEADER)
