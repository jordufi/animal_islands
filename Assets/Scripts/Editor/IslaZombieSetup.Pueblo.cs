    // Tracas ('%'): the post stands on the marker; the string hangs along the longest straight run of street from it.
    const int TracaMaxCells = 8;

    static void PueBuildTracas(Transform root, Layout L, Material wood)
    {
        var parent = Child(root, "Tracas", Vector3.zero).transform;
        var red = M("VJ_Rojo", new Color(0.78f, 0.1f, 0.1f));
        var cable = M("VJ_Cable", new Color(0.04f, 0.04f, 0.04f));
        int n = 0;
        foreach (var cell in Cells(L))
        {
            if (L.At(cell.x, cell.y) != '%') continue;
            Vector2Int best = Vector2Int.zero;
            int bestLen = 0;
            foreach (var d in Dirs)
            {
                int k = 0;
                while (k < TracaMaxCells && VenWalk(L, cell.x + d.x * (k + 1), cell.y + d.y * (k + 1)) && !IsDoor(L.At(cell.x + d.x * (k + 1), cell.y + d.y * (k + 1)))
                       && !L.IsRamp(cell.x + d.x * (k + 1), cell.y + d.y * (k + 1))) k++;
                if (k > bestLen) { bestLen = k; best = d; }
            }
            if (bestLen < 2) { Debug.LogError($"[Villajubilada] traca at {cell} has no straight street beside it"); continue; }
            Vector3 a = World(cell.x, cell.y), b = World(cell.x + best.x * bestLen, cell.y + best.y * bestLen) + GridDir(best) * (Cell / 2f - 0.2f);
            var go = Child(parent, "Traca" + (n++), a);
            Box(go.transform, "Poste", a, new Vector3(0.14f, 2.7f, 0.14f), wood, 0f, false);
            Box(go.transform, "Poste_Fin", b, new Vector3(0.14f, 2.7f, 0.14f), wood, 0f, false);
            var strand = Child(go.transform, "Ristra", a).transform;
            float len = Vector3.Distance(a, b);
            var line = Box(strand, "Cuerda", (a + b) / 2f + Vector3.up * 2.45f, new Vector3(0.03f, 0.03f, len), cable, 0f, false);
            line.transform.rotation = Quaternion.LookRotation((b - a).normalized);
            for (float d = 0.3f; d < len; d += 0.35f)
                Box(strand, "Petardo", Vector3.Lerp(a, b, d / len) + Vector3.up * 2.25f, new Vector3(0.07f, 0.2f, 0.07f), red, 0f, false);
            var label = WorldLabel.Create(go.transform, new Vector3(0f, 3f, 0f), "", 0.26f, new Color(1f, 0.6f, 0.2f));
            var trap = go.AddComponent<TracaTrap>();
            trap.Configure(a, b, strand, label);
            EditorUtility.SetDirty(trap);
        }
    }

    // The encierro: the route of the [route] line (cell corners between the two lanes of the street) sampled every
    // metre, the Porton ('Q') with its two leaves, old ladies at the windows of the Calle del Encierro, a line of
    // sawdust on the ground so the route always shows.
    static void PueBuildEncierro(Transform root, Layout L, Dictionary<char, Zone> zones, List<BuiltDoor> doors, EncierroData encData, Material wood, Material dark)
    {
        var lines = File.ReadAllLines(LayoutPath);
        int at = System.Array.FindIndex(lines, l => l.Trim() == "[route]");
        if (at < 0 || at + 1 >= lines.Length) { Debug.LogError("[Villajubilada] the layout has no [route] line"); return; }
        var parts = lines[at + 1].Split('|');
        var corners = parts[0].Trim().Split(' ').Where(s => s.Length > 0).Select(s => { var f = s.Split(','); return new Vector2(int.Parse(f[0]) - 0.5f, int.Parse(f[1]) - 0.5f); }).ToList();   // a corner = between cells
        int ringCorner = int.Parse(parts[1].Trim());

        var parent = Child(root, "Encierro", Vector3.zero).transform;
        var samples = new List<Vector3>();
        var sZone = new List<Zone>();
        var sDoor = new List<ZoneDoor>();
        int ringFrom = 0;
        void Add(Vector2 g)
        {
            // the cell just west / north of the line (the line runs on the boundary between the two lanes)
            var cell = new Vector2Int(Mathf.RoundToInt(g.x - 0.01f), Mathf.RoundToInt(g.y - 0.01f));
            char ch = L.At(cell.x, cell.y);
            samples.Add(Flat(World(g.x, g.y)) + Vector3.up * L.Y(cell.x, cell.y));
            sZone.Add(zones.TryGetValue(L.cellZone[cell.x, cell.y], out var z) ? z : null);
            sDoor.Add(IsDoor(ch) ? doors.FirstOrDefault(d => d.def.digit == ch)?.door : null);
        }
        for (int i = 0; i + 1 < corners.Count; i++)
        {
            if (i == ringCorner) ringFrom = samples.Count;
            float len = (corners[i + 1] - corners[i]).magnitude * Cell;
            int steps = Mathf.Max(1, Mathf.RoundToInt(len));
            for (int k = 0; k < steps; k++) Add(Vector2.Lerp(corners[i], corners[i + 1], k / (float)steps));
        }
        Add(corners[corners.Count - 1]);

        // sawdust line on the ground along the whole route
        var dust = M("VJ_Serrin", new Color(0.78f, 0.62f, 0.32f));
        for (int i = 0; i + 1 < corners.Count; i++)
        {
            Vector3 a = Flat(World(corners[i].x, corners[i].y)), b = Flat(World(corners[i + 1].x, corners[i + 1].y));
            var strip = Box(parent, "Serrin", (a + b) / 2f, new Vector3(0.5f, 0.02f, Vector3.Distance(a, b) + 0.5f), dust, 0.005f, false);
            strip.transform.rotation = Quaternion.LookRotation((b - a).normalized);
        }

        // the Porton: two timber leaves hinged on the walls beside the 'Q' cells (its blocker is added after the bake)
        var qs = Rects(L, (c, row) => L.At(c, row) == 'Q');
        EncierroGate gate = null;
        int gateIndex = 0;
        if (qs.Count == 1)
        {
            var r = qs[0];
            Vector3 centre = RectCenter(r);
            float half = r.width * Cell / 2f;
            var g = Child(parent, "Porton", centre);
            Transform Leaf(string name, float side)
            {
                var pivot = Child(g.transform, name, centre + Vector3.right * side * half).transform;
                var leaf = Box(pivot, "Hoja", centre + Vector3.right * side * half / 2f, new Vector3(half - 0.04f, 3f, 0.14f), wood, 0f, false);
                for (int i = 0; i < 3; i++) Box(leaf.transform, "Herraje", centre + Vector3.right * side * half / 2f + Vector3.up * (0.5f + i), new Vector3(half - 0.04f, 0.1f, 0.18f), dark, 0f, false);
                return pivot;
            }
            var label = WorldLabel.Create(g.transform, new Vector3(0f, 3.6f, 0f), "", 0.3f, new Color(1f, 0.85f, 0.4f));
            gate = g.AddComponent<EncierroGate>();
            gate.Configure(null, Leaf("Hoja_Izq", -1f), Leaf("Hoja_Der", 1f), label);
            foreach (float s in new[] { -1f, 1f }) Box(g.transform, "Poste", centre + Vector3.right * s * (half + 0.12f), new Vector3(0.3f, 3.4f, 0.3f), wood, 0f, false);
            gateIndex = Enumerable.Range(0, samples.Count).OrderBy(i => (Flat(samples[i]) - Flat(centre)).sqrMagnitude).First();
            EditorUtility.SetDirty(gate);
        }
        else Debug.LogError($"[Villajubilada] the Porton must be one straight run of 'Q' cells (found {qs.Count})");

        // old ladies at the windows: every 6 m of the Calle del Encierro, alternating sides, where there is a house
        var skin = M("VJ_Piel", new Color(0.9f, 0.7f, 0.58f));
        var hair = M("VJ_Canas", new Color(0.82f, 0.82f, 0.85f));
        var robe = M("VJ_Bata", new Color(0.75f, 0.45f, 0.65f));
        var windows = new List<Transform>();
        for (int i = gateIndex + 4; i < ringFrom - 2; i += 6)
        {
            Vector3 dir = (samples[i + 1] - samples[i]).normalized, side = new Vector3(dir.z, 0f, -dir.x);
            foreach (float s in windows.Count % 2 == 0 ? new[] { 1f, -1f } : new[] { -1f, 1f })
            {
                var house = CellOf(samples[i] + side * s * 3f);
                if (L.At(house.x, house.y) != '#') continue;
                Vector3 wall = samples[i] + side * s * Cell;   // the facade plane: one cell from the centre line
                var w = Child(parent, "Ventana" + windows.Count, wall - side * s * 0.25f + Vector3.up * 3.7f);
                w.transform.rotation = Quaternion.LookRotation(-side * s);
                Box(w.transform, "Hueco", wall + side * s * 0.02f + Vector3.up * 3.1f, Mathf.Abs(side.x) > 0.5f ? new Vector3(0.06f, 1.5f, 1.2f) : new Vector3(1.2f, 1.5f, 0.06f), dark, 0f, false);
                Box(w.transform, "Bata", wall - side * s * 0.12f + Vector3.up * 3.15f, new Vector3(0.55f, 0.6f, 0.4f), robe, 0f, false).transform.rotation = w.transform.rotation;
                TestMapSetup.Prim(PrimitiveType.Sphere, w.transform, new Vector3(0f, 0.2f, 0f), Vector3.one * 0.42f, skin);
                TestMapSetup.Prim(PrimitiveType.Sphere, w.transform, new Vector3(0f, 0.34f, -0.08f), new Vector3(0.44f, 0.36f, 0.4f), hair);
                windows.Add(w.transform);
                break;
            }
        }

        var lorry = root.Find("Props/Camion");
        var enc = parent.gameObject.AddComponent<Encierro>();
        enc.Configure(encData, samples.ToArray(), ringFrom, gateIndex, sZone.ToArray(), sDoor.ToArray(),
            PueStartZones.Where(zones.ContainsKey).Select(c => zones[c]).ToArray(), zones.TryGetValue('c', out var street) ? street : null,
            gate, VN("VJ_Toro"), VN("VJ_Toro_Patas"), lorry, windows.ToArray(), root.Find("PlayerSpawn"), PuePaidStartZones.Where(zones.ContainsKey).Select(c => zones[c]).ToArray());
        EditorUtility.SetDirty(enc);
    }

    // Fiesta lights: per zone, every renderer with bulbs (garlands, rides, the bandstand) sorted from the zone's fuse
    // box outwards, plus up to four real lights spread over the zone. Las Eras has no fuse box: its lights follow the
    // whole village (BoatMission.ZoneLit falls back to Power).
    static void PueBuildLights(Transform root, Layout L, Dictionary<char, Zone> zones)
    {
        var parent = Child(root, "Luces", Vector3.zero).transform;
        string[] slots = { "VJ_Bulb_R", "VJ_Bulb_Y", "VJ_Bulb_G", "VJ_Bulb_B" };
        var on = new[]
        {
            TestMapSetup.Mat("VJ_Bulb_R_On", new Color(1f, 0.2f, 0.15f), 1.6f), TestMapSetup.Mat("VJ_Bulb_Y_On", new Color(1f, 0.85f, 0.25f), 1.6f),
            TestMapSetup.Mat("VJ_Bulb_G_On", new Color(0.25f, 1f, 0.35f), 1.6f), TestMapSetup.Mat("VJ_Bulb_B_On", new Color(0.3f, 0.55f, 1f), 1.6f),
        };
        foreach (var m in on)   // URP switches _EMISSION off on a material whose GI flag says "emissive is black"
        {
            m.globalIlluminationFlags = MaterialGlobalIlluminationFlags.BakedEmissive;
            m.EnableKeyword("_EMISSION");
            EditorUtility.SetDirty(m);
        }
        var tints = new[] { new Color(1f, 0.78f, 0.5f), new Color(1f, 0.6f, 0.75f), new Color(1f, 0.85f, 0.55f), new Color(0.65f, 0.8f, 1f) };
        var bulbs = root.GetComponentsInChildren<Renderer>().Where(r => r.sharedMaterials.Any(m => m != null && m.name.StartsWith("VJ_Bulb"))).ToList();
        var switches = root.GetComponentsInChildren<PowerSwitch>();
        var windowOn = TestMapSetup.Mat("VJ_Ventana_On", new Color(1f, 0.8f, 0.42f), 1.4f);
        windowOn.globalIlluminationFlags = MaterialGlobalIlluminationFlags.BakedEmissive;
        windowOn.EnableKeyword("_EMISSION");
        EditorUtility.SetDirty(windowOn);
        int total = 0, lightCount = 0, windowsTotal = 0;
        foreach (var zd in L.zones)
        {
            if (PueStartZones.IndexOf(zd.letter) >= 0 && zd.letter != 'r') continue;   // the start zones are lost (the bar has a fuse box)
            var zone = zones[zd.letter];
            var sw = switches.FirstOrDefault(s => s.Zone == zone);
            var floor = Cells(L).Where(c => L.cellZone[c.x, c.y] == zd.letter && VenWalk(L, c.x, c.y)).ToList();
            if (floor.Count == 0) continue;
            Vector3 origin = sw != null ? sw.transform.position : World(floor[0].x, floor[0].y);
            var mine = bulbs.Where(r => { var c = CellOf(r.bounds.center); return L.InGrid(c.x, c.y) && L.cellZone[c.x, c.y] == zd.letter; })
                .OrderBy(r => (r.bounds.center - origin).sqrMagnitude).ToArray();
            var holder = Child(parent, "Luces_" + zd.id, origin);
            // farthest-point sampling: the lights spread over the zone
            var picked = new List<Vector3>();
            int want = Mathf.Clamp(floor.Count / 12 + 1, 1, 12);   // the PC renderer is Forward+: many small lights are fine
            Vector3 last = origin;
            for (int i = 0; i < want; i++)
            {
                var c = floor.OrderByDescending(f => picked.Count == 0 ? -(World(f.x, f.y) - origin).sqrMagnitude * 0f + Hash(f.x, f.y, 70) : picked.Min(q => (World(f.x, f.y) - q).sqrMagnitude)).First();
                last = World(c.x, c.y);
                picked.Add(last);
            }
            var lights = new List<Light>();
            for (int i = 0; i < picked.Count; i++)
            {
                var l = new GameObject("Luz" + i).AddComponent<Light>();
                l.transform.SetParent(holder.transform, false);
                l.transform.position = picked[i] + Vector3.up * 3.9f;
                l.type = LightType.Point; l.range = 14f; l.intensity = 0f; l.color = tints[(i + zd.letter) % tints.Length]; l.shadows = LightShadows.None;
                l.enabled = false;
                lights.Add(l);
            }
            var fl = holder.AddComponent<FiestaLights>();
            fl.Configure(zone, mine, lights.ToArray(), slots, on);
            // about half the house fronts of the zone light their windows (the strip faces the street: the cell in front)
            var fac = root.Find("Fachadas");
            if (fac != null)
            {
                var strips = fac.Cast<Transform>().Where(t =>
                {
                    var c = CellOf(t.position + t.forward * 1f);
                    return L.InGrid(c.x, c.y) && L.cellZone[c.x, c.y] == zd.letter && VenWalk(L, c.x, c.y) && Hash(Mathf.RoundToInt(t.position.x * 2f), Mathf.RoundToInt(t.position.z * 2f), 77) < 0.5f;
                }).SelectMany(t => t.GetComponentsInChildren<Renderer>()).Where(r => r.sharedMaterials.Any(m => m != null && m.name.StartsWith("VN_Glass"))).ToArray();
                fl.SetWindows(strips, windowOn);
                windowsTotal += strips.Length;
            }
            EditorUtility.SetDirty(fl);
            total += mine.Length;
            lightCount += lights.Count;
        }
        Debug.Log($"[Villajubilada] fiesta lights: {total} strings / rides with bulbs, {lightCount} real lights, {windowsTotal} house fronts with lit windows");
    }

    // ------------------------------------------------------------------ after the NavMesh bake and the map checks
    // The Porton blocks from the first second (collider + carving obstacle): added now, like the door obstacles, so
    // the bake and the checks see La Parada and the Calle Mayor as one piece (they are one group in the layout).
    static List<string> PueAfterChecks(Transform root, Layout L)
    {
        var rep = new List<string>();
        var gate = root.GetComponentInChildren<EncierroGate>();
        var enc = root.GetComponentInChildren<Encierro>();
        if (gate == null || enc == null) { rep.Add("ERROR: no Encierro / Porton in the scene"); return rep; }
        var qs = Rects(L, (c, row) => L.At(c, row) == 'Q');
        var r = qs[0];
        var wall = Child(gate.transform, "Bloqueo", RectCenter(r) + Vector3.up * ColliderHeight / 2f);
        wall.layer = TestMapSetup.WallLayer;
        wall.AddComponent<BoxCollider>().size = new Vector3(r.width * Cell, ColliderHeight, 0.4f);
        var ob = wall.AddComponent<NavMeshObstacle>();
        ob.shape = NavMeshObstacleShape.Box;
        ob.size = new Vector3(r.width * Cell + 0.4f, 3f, 0.6f);
        ob.center = new Vector3(0f, -ColliderHeight / 2f + 1.5f, 0f);
        ob.carving = true;
        ob.carveOnlyStationary = true;
        var so = new SerializedObject(gate);
        so.FindProperty("blocker").objectReferenceValue = wall;
        so.ApplyModifiedPropertiesWithoutUndo();

        // the whole route lies on the street (NavMesh under every sample) and is clear of props
        int off = 0, blocked = 0;
        var route = enc.Route;
        for (int i = 0; i < route.Length; i++)
        {
            if (i > 3 && !NavAgents.Sample(route[i], 0.6f, out _)) off++;   // the first samples are under the lorry
            if (i > 3 && Physics.CheckSphere(route[i] + Vector3.up * 1.2f, 0.5f, (1 << TestMapSetup.WallLayer) | (1 << NavAgents.PropLayer), QueryTriggerInteraction.Ignore)
                && (route[i] - wall.transform.position).magnitude > 6f) blocked++;
        }
        float stem = 0f, ring = 0f;
        for (int i = 1; i < route.Length; i++) { if (i <= enc.RingFrom) stem += Vector3.Distance(route[i - 1], route[i]); else ring += Vector3.Distance(route[i - 1], route[i]); }
        rep.Add((off == 0 && blocked == 0 ? "OK " : "ERROR:") + $" encierro route: {route.Length} samples, lorry -> ring {stem:0} m, ring {ring:0} m, {off} samples off the NavMesh, {blocked} inside something solid");
        int wins = root.Find("Encierro").Cast<Transform>().Count(t => t.name.StartsWith("Ventana"));
        rep.Add((wins >= 4 ? "OK " : "WARNING:") + $" {wins} windows with old ladies along the Calle del Encierro");
        int tracas = root.GetComponentsInChildren<TracaTrap>().Length, boxes = root.GetComponentsInChildren<PowerSwitch>().Count(s => s.Zone != null);
        var lights = root.GetComponentsInChildren<FiestaLights>();
        rep.Add($"OK  {tracas} tracas, {boxes} fuse boxes, fiesta lights in {lights.Length} zones ({lights.Sum(l => l.BulbCount)} strings / rides)");
        var lighters = root.GetComponentsInChildren<MissionTask>().Count(t => t.name.StartsWith("Mechero_"));
        rep.Add((lighters == 2 ? "OK " : "ERROR:") + $" {lighters} lighter spots in the paid start zones (the one opened second has it)");
        return rep;
    }
