    static void PueBuildProps(Transform root, Layout L)
    {
        var pr = Child(root, "Props", Vector3.zero).transform;
        Child(root, "PropColliders", Vector3.zero);
        var awnings = new[] { M("VN_Toldo_Rojo", new Color(0.75f, 0.2f, 0.15f)), M("VN_Toldo_Verde", new Color(0.18f, 0.45f, 0.3f)), M("VN_Toldo_Azul", new Color(0.2f, 0.35f, 0.65f)), M("VJ_Toldo_Amarillo", new Color(0.95f, 0.75f, 0.2f)) };

        foreach (var r in Rects(L, (c, row) => L.At(c, row) == 'V'))   // the cattle lorry: tailgate to the north
        {
            var lorry = VenPlace(pr, VN("VJ_Camion"), RectCenter(r), 90f);
            if (lorry != null) { lorry.name = "Camion"; PartColliders(lorry); }
        }

        foreach (var r in Rects(L, (c, row) => L.At(c, row) == 'o'))
        {
            char z = L.cellZone[r.x, r.y];
            if (z == 'f' && r.width >= 4 && r.height >= 4) { PartColliders(PlaceInRect(pr, VN("VJ_CochesChoque"), RectCenter(r), r.width * Cell - 0.1f, r.height * Cell - 0.1f)); continue; }
            if (z == 'f' && r.width >= 3 && r.height >= 3) { PartColliders(PlaceInRect(pr, VN("VJ_Noria"), RectCenter(r), r.width * Cell - 0.1f, r.height * Cell - 0.1f)); continue; }
            if (z == 'f' && r.width * r.height == 2) { PartColliders(Repaint(PlaceInRect(pr, VN("VJ_Churreria"), RectCenter(r), r.width * Cell - 0.1f, r.height * Cell - 0.1f, 180f), "VN_AwningPaint", awnings[3])); continue; }
            foreach (var cell in Cells(r))
            {
                var p = World(cell.x, cell.y);
                float h = Hash(cell.x, cell.y);
                var paint = awnings[(int)(h * 97) % awnings.Length];
                switch (z)
                {
                    case 'p':   // the arcade of the town hall (a row of columns) and the fountain (alone)
                        bool row = Enumerable.Range(1, 3).Any(i => L.At(cell.x + i, cell.y) == 'o' || L.At(cell.x - i, cell.y) == 'o');
                        PartColliders(PlaceInRect(pr, VN(row ? "VJ_Columna" : "VJ_Fuente"), p, row ? 1.0f : 1.9f, row ? 1.0f : 1.9f));
                        break;
                    case 'e': PartColliders(PlaceInRect(pr, VN("VJ_Columna"), p, 1.0f, 1.0f)); break;   // the cross of the atrium
                    case 'a': PartColliders(PlaceInRect(pr, VN("VJ_Marquesina"), p, 1.95f, 1.95f, FaceOpen(L, cell), 0f, 0f, false)); break;
                    case 'r': PartColliders(Repaint(PlaceInRect(pr, VN("VJ_Barra"), p, 1.95f, 1.95f, 180f), "VN_AwningPaint", awnings[0])); break;   // the bar: counter to the south
                    case 'f': PartColliders(Repaint(PlaceInRect(pr, VN("VJ_Puesto"), p, 1.95f, 1.95f, FaceOpen(L, cell)), "VN_AwningPaint", paint)); break;
                    default: PartColliders(PlaceInRect(pr, VN("VJ_Paca"), p, 1.9f, 1.9f, Mathf.Floor(h * 4f) * 90f)); break;
                }
            }
        }

        foreach (var cell in Cells(L))
        {
            if (L.At(cell.x, cell.y) != 'x') continue;
            var p = World(cell.x, cell.y);
            // 'x' = low cover: always jumpable, every collider stops at LowCoverTop (checked by CheckProps)
            CapColliders(PartColliders(PlaceInRect(pr, VN("VJ_Mesa"), p, 1.9f, 1.9f, Mathf.Floor(Hash(cell.x, cell.y, 4) * 2f) * 90f, 0f, 0f, false), NavAgents.PropLayer, 0.25f), p.y + LowCoverTop);
        }

        // the roof of the bandstand over its raised platform (level 1 block of the plaza) and the tractor of the way out
        foreach (var r in Rects(L, (c, row) => L.cellZone[c, row] == 'p' && VenWalk(L, c, row) && !L.IsRamp(c, row) && L.level[c, row] == 1))
            VenPlace(pr, VN("VJ_Templete"), Flat(RectCenter(r)) + Vector3.up * LevelH, 0f, r.width * Cell / 8f);
        foreach (var cell in Cells(L))
            if (L.At(cell.x, cell.y) == 'X')
            {
                var tractor = VenPlace(pr, VN("VJ_Tractor"), World(cell.x, cell.y) + Vector3.back * 5f, 90f);   // along the wall, the trailer beside the way out
                if (tractor != null) { tractor.name = "Tractor"; PartColliders(tractor); }
            }
    }

    // ------------------------------------------------------------------ decoration: garlands of bulbs and bunting
    const float GarlandY = 4.4f;

    static void PueBuildDecor(Transform root, Layout L)
    {
        var dr = Child(root, "Decor", Vector3.zero).transform;
        int n = 0;
        // a string from wall to wall wherever the street is 1 to 3 cells wide, every second cell along it
        foreach (var cell in Cells(L))
        {
            int c = cell.x, r = cell.y;
            if (!VenWalk(L, c, r)) continue;
            foreach (bool across in new[] { true, false })   // across = the string runs east-west
            {
                Vector2Int d = across ? new Vector2Int(1, 0) : new Vector2Int(0, 1);
                if (!IsSolid(L.At(c - d.x, r - d.y)) || (across ? r : c) % 2 != 0) continue;
                int k = 0;
                float y = 0f;
                bool ramp = false;
                while (VenWalk(L, c + d.x * k, r + d.y * k)) { y = Mathf.Max(y, L.Y(c + d.x * k, r + d.y * k)); ramp |= L.IsRamp(c + d.x * k, r + d.y * k); k++; }
                if (k > 3 || ramp || !IsSolid(L.At(c + d.x * k, r + d.y * k))) continue;
                var mid = Flat(World(c + d.x * (k - 1) / 2f, r + d.y * (k - 1) / 2f)) + Vector3.up * (y + GarlandY);
                var g = VenPlace(dr, VN("VJ_Guirnalda"), mid, across ? 0f : 90f);
                if (g == null) continue;
                g.name = "Guirnalda";
                g.transform.localScale = new Vector3(k * Cell / 4f, 1f, 1f);
                n++;
            }
        }
        Debug.Log($"[Villajubilada] {n} garlands");
    }

