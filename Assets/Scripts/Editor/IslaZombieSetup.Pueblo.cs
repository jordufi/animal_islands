            task.Configure(kind, before.gameObject, after.gameObject, tm);
            after.gameObject.SetActive(false);
            EditorUtility.SetDirty(task);
            return task;
        }
        Vector3 WallSide(Vector2Int cell)
        {
            var side = Dirs.FirstOrDefault(d => IsSolid(L.At(cell.x + d.x, cell.y + d.y)));
            return side == Vector2Int.zero ? Vector3.forward : GridDir(side);
        }
